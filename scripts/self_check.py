def main() -> int:
    watchlists = {w["id"]: w for w in c.resolve_watchlists()}
    不一致 = 0

    print(f"{'':2} {'監視リスト':<28} {'所在地':<34} {'価格':>12}  メモ")
    print("-" * 100)
    for wl_id, 所在地, 価格, 種目, 期待, メモ in テストケース:
        wl = watchlists.get(wl_id)
        if wl is None:
            print(f"?? 監視リスト '{wl_id}' が見つかりません（無効化されている可能性）")
            不一致 += 1
            continue
        item = {"所在地": 所在地, "物件種目": 種目, "価格万円": float(価格), "_raw": {}}
        実際 = c.matches(item, wl)
        印 = "○" if 実際 else "×"
        ずれ = "" if 実際 == 期待 else f"  ←★期待は{'○' if 期待 else '×'}"
        if 実際 != 期待:
            不一致 += 1
        print(f"{印:2} {wl['名称']:<28} {所在地:<34} {c.金額表示(価格):>12}  {メモ}{ずれ}")

    print("-" * 100)
    if 不一致:
        print(f"想定と違う判定が {不一致} 件あります。config/watchlists.json を確認してください。")
        return 1
    print(f"全 {len(テストケース)} 件、想定どおりです。")
    return 0


